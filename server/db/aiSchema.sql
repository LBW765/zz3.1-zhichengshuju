CREATE TABLE IF NOT EXISTS ai_users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password VARCHAR(100) NOT NULL,
  display_name VARCHAR(120) NOT NULL,
  company VARCHAR(160) NOT NULL DEFAULT '',
  role ENUM('enterprise','operations','government') NOT NULL,
  status TINYINT NOT NULL DEFAULT 1,
  created_by INT DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_tokens (
  id INT AUTO_INCREMENT PRIMARY KEY,
  token_hash CHAR(64) NOT NULL UNIQUE,
  user_id INT NOT NULL,
  expires_at DATETIME NOT NULL,
  created_by INT DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES ai_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_demands (
  id INT AUTO_INCREMENT PRIMARY KEY,
  demand_no VARCHAR(40) UNIQUE,
  title VARCHAR(100) NOT NULL,
  demand_type VARCHAR(30) NOT NULL,
  industry VARCHAR(40) NOT NULL,
  scene VARCHAR(500) NOT NULL,
  description TEXT NOT NULL,
  tags JSON,
  budget_min DECIMAL(12,2) DEFAULT NULL,
  budget_max DECIMAL(12,2) DEFAULT NULL,
  period_months INT NOT NULL,
  region VARCHAR(80) NOT NULL DEFAULT '吉安市',
  deadline DATE DEFAULT NULL,
  company VARCHAR(160) NOT NULL,
  contact VARCHAR(80) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT '已发布',
  seed_record TINYINT NOT NULL DEFAULT 0,
  created_by INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_demand_owner (created_by, created_at),
  INDEX idx_demand_industry (industry, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_suppliers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(160) NOT NULL,
  provider VARCHAR(160) NOT NULL,
  industry VARCHAR(40) NOT NULL,
  description TEXT NOT NULL,
  tags JSON,
  budget_min DECIMAL(12,2) DEFAULT NULL,
  budget_max DECIMAL(12,2) DEFAULT NULL,
  period_months INT NOT NULL,
  seed_record TINYINT NOT NULL DEFAULT 0,
  created_by INT DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_supplier_industry (industry)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_catalog_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  category VARCHAR(40) NOT NULL,
  title VARCHAR(160) NOT NULL,
  subtype VARCHAR(60) NOT NULL DEFAULT '',
  summary VARCHAR(500) NOT NULL DEFAULT '',
  body TEXT,
  provider VARCHAR(160) NOT NULL DEFAULT '',
  industry VARCHAR(40) NOT NULL DEFAULT '',
  deadline DATE DEFAULT NULL,
  status VARCHAR(40) NOT NULL DEFAULT '开放中',
  metadata JSON,
  seed_record TINYINT NOT NULL DEFAULT 0,
  created_by INT DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_catalog_category (category, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_attachments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  original_name VARCHAR(160) NOT NULL,
  stored_name VARCHAR(100) NOT NULL UNIQUE,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes INT NOT NULL,
  created_by INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_applications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  application_no VARCHAR(40) UNIQUE,
  application_type VARCHAR(40) NOT NULL,
  target_type VARCHAR(40) NOT NULL,
  target_id INT DEFAULT NULL,
  demand_id INT DEFAULT NULL,
  supplier_id INT DEFAULT NULL,
  title VARCHAR(160) NOT NULL,
  company VARCHAR(160) NOT NULL,
  contact VARCHAR(80) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  description TEXT NOT NULL,
  service_type VARCHAR(60) NOT NULL DEFAULT '',
  environment_id INT DEFAULT NULL,
  attachment_name VARCHAR(160) NOT NULL DEFAULT '',
  attachment_path VARCHAR(500) NOT NULL DEFAULT '',
  attachment_id INT DEFAULT NULL,
  status VARCHAR(30) NOT NULL DEFAULT '待受理',
  return_reason TEXT,
  handler_id INT DEFAULT NULL,
  seed_record TINYINT NOT NULL DEFAULT 0,
  created_by INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_application_owner (created_by, created_at),
  INDEX idx_application_status (status, created_at),
  FOREIGN KEY (demand_id) REFERENCES ai_demands(id) ON DELETE SET NULL,
  FOREIGN KEY (supplier_id) REFERENCES ai_suppliers(id) ON DELETE SET NULL,
  FOREIGN KEY (attachment_id) REFERENCES ai_attachments(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_application_events (
  id INT AUTO_INCREMENT PRIMARY KEY,
  application_id INT NOT NULL,
  from_status VARCHAR(30) NOT NULL DEFAULT '',
  to_status VARCHAR(30) NOT NULL,
  actor_id INT NOT NULL,
  actor_name VARCHAR(120) NOT NULL,
  note TEXT,
  created_by INT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (application_id) REFERENCES ai_applications(id) ON DELETE CASCADE,
  INDEX idx_event_application (application_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_metrics (
  id INT AUTO_INCREMENT PRIMARY KEY,
  metric_key VARCHAR(50) NOT NULL UNIQUE,
  label VARCHAR(80) NOT NULL,
  value DECIMAL(14,2) NOT NULL,
  unit VARCHAR(20) NOT NULL DEFAULT '',
  note VARCHAR(160) NOT NULL DEFAULT '',
  kind ENUM('demo','target') NOT NULL DEFAULT 'demo',
  created_by INT DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
